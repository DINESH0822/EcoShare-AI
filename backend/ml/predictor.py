"""
Inference runner for trained Random Forest Claim Predictor
Accepts JSON string arguments and outputs probability & explanation.
"""

import sys
import os
import json
import joblib
import numpy as np
import pandas as pd
import sklearn

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
MODEL_PATH = os.path.join(BASE_DIR, "models", "claim_predictor.joblib")

def load_model():
    if not os.path.exists(MODEL_PATH):
        return None
    return joblib.load(MODEL_PATH)

def predict(data, artifact=None):
    artifact = artifact if artifact is not None else load_model()
    if artifact is None:
        return {
            "success": False,
            "error": "Model artifact not found. Please train model first."
        }

    if not isinstance(data, dict):
        return {"success": False, "error": "Prediction input must be a JSON object."}

    clf = artifact["model"]
    categories = artifact["categories"]
    cat_map = {c: i for i, c in enumerate(categories)}

    def numeric_value(name, default, minimum, maximum):
        value = data.get(name, default)
        if isinstance(value, bool):
            raise ValueError(f"{name} must be a finite number.")
        try:
            number = float(value)
        except (TypeError, ValueError) as error:
            raise ValueError(f"{name} must be a finite number.") from error
        if not np.isfinite(number) or number < minimum or number > maximum:
            raise ValueError(f"{name} must be between {minimum} and {maximum}.")
        return number

    distance_km = numeric_value("distance_km", 5.0, 0, 500)
    quantity = numeric_value("quantity", 50, 1, 1_000_000)
    remaining_shelf_life_hours = numeric_value("remaining_shelf_life_hours", 4.0, 0, 8760)
    ngo_capacity = numeric_value("ngo_capacity", 200, 1, 1_000_000)
    capacity_ratio = quantity / max(1, ngo_capacity)
    category = data.get("category", "cooked_meals")
    if not isinstance(category, str):
        raise ValueError("category must be a string.")
    category_encoded = cat_map.get(category, cat_map.get("other", 0))

    def boolean_value(name):
        value = data.get(name, False)
        if value not in (True, False, 0, 1):
            raise ValueError(f"{name} must be a boolean or 0/1.")
        return int(value)

    is_emergency = boolean_value("is_emergency")
    requires_refrigeration = boolean_value("requires_refrigeration")

    feature_values = [[
        distance_km,
        quantity,
        remaining_shelf_life_hours,
        ngo_capacity,
        capacity_ratio,
        category_encoded,
        is_emergency,
        requires_refrigeration
    ]]
    feature_row = pd.DataFrame(feature_values, columns=artifact["features"])

    prob = float(clf.predict_proba(feature_row)[0][1])
    score = int(round(prob * 100))
    
    # Explainable factors
    explanations = []
    if distance_km <= 8.0:
        explanations.append(f"Close proximity ({distance_km:.1f} km) increases prompt dispatch chance.")
    elif distance_km > 20.0:
        explanations.append(f"Extended transit distance ({distance_km:.1f} km) presents pickup challenge.")
        
    if remaining_shelf_life_hours >= 3.0:
        explanations.append(f"Sufficient rescue window ({remaining_shelf_life_hours:.1f} hrs) allows regular coordination.")
    else:
        explanations.append(f"Tight window ({remaining_shelf_life_hours:.1f} hrs) demands rapid response.")
        
    if capacity_ratio <= 0.6:
        explanations.append(f"Organization capacity comfortably covers donation ({quantity} servings).")
        
    return {
        "success": True,
        "claimProbability": prob,
        "mlScore": score,
        "modelVersion": artifact["version"],
        "algorithm": artifact["algorithm"],
        "metrics": artifact["metrics"],
        "metricScope": artifact.get(
            "metric_scope",
            "Stored holdout metrics from a synthetic, formula-labeled dataset; not real-world performance."
        ),
        "datasetProvenance": artifact.get(
            "dataset_provenance",
            "Synthetic examples generated by train_claim_predictor.py; labels sampled from a hand-written logistic formula."
        ),
        "trainingScikitLearnVersion": artifact.get("training_scikit_learn_version"),
        "features": artifact["features"],
        "runtimeScikitLearnVersion": sklearn.__version__,
        "explanations": explanations,
        "predictionSource": "python-model"
    }

def serve():
    artifact = load_model()
    if artifact is None:
        print(json.dumps({
            "type": "ready",
            "success": False,
            "error": "Model artifact not found."
        }), flush=True)
        return

    print(json.dumps({"type": "ready", "success": True}), flush=True)
    for line in sys.stdin:
        request_id = None
        try:
            request = json.loads(line)
            request_id = request.get("id") if isinstance(request, dict) else None
            if not isinstance(request, dict):
                raise ValueError("Worker request must be a JSON object.")
            result = predict(request.get("input"), artifact)
            response = {"id": request_id, "result": result}
        except Exception as error:
            response = {
                "id": request_id,
                "result": {"success": False, "error": f"Prediction failed: {error}"}
            }
        print(json.dumps(response), flush=True)

if __name__ == "__main__":
    if len(sys.argv) > 1 and sys.argv[1] == "--server":
        serve()
        sys.exit(0)
    if len(sys.argv) > 1:
        try:
            input_data = json.loads(sys.argv[1])
            res = predict(input_data)
            print(json.dumps(res))
        except Exception as e:
            print(json.dumps({"success": False, "error": f"Prediction failed: {e}"}))
    else:
        # Default test run
        test_res = predict({
            "distance_km": 4.5,
            "quantity": 80,
            "remaining_shelf_life_hours": 4.5,
            "ngo_capacity": 300,
            "category": "cooked_meals",
            "is_emergency": False,
            "requires_refrigeration": False
        })
        print(json.dumps(test_res, indent=2))
